void (async () => {
  if (window.__PIXOMA_WORKSPACE_RESIZE_RUNNING__) return
  window.__PIXOMA_WORKSPACE_RESIZE_RUNNING__ = true
  const invoke = window.__TAURI_INTERNALS__.invoke
  const emit = (event, payload) => invoke('plugin:event|emit', { event, payload })
  const request = (method, path, body = null) => invoke('studio_request', { request: { method, path, body } })
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
  const wait = async (condition, message) => { const end = Date.now() + 60000; while (!await condition()) { if (Date.now() > end) throw new Error(message); await delay(100) }; await delay(100) }
  const aria = label => document.querySelector(`[aria-label="${label}"]`)
  const tab = label => [...document.querySelectorAll('[role="tab"]')].find(element => element.textContent.trim() === label)
  const choose = label => tab(label).dispatchEvent(new MouseEvent('mousedown', { bubbles: true, button: 0, ctrlKey: false }))
  const chatWidth = () => document.querySelector('.studio-chat-root').getBoundingClientRect().width
  const measurements = []
  await emit('studio:layout-progress', { stage: 'start' })
  await wait(() => document.querySelector('[data-slot="studio-page"]'), 'Studio 没有启动')
  await emit('studio:layout-progress', { stage: 'ready' })
  const session = await request('POST', '/api/v1/studio/sessions', { request_id: 'native-workspace-resize-20261101' })
  await emit('studio:layout-progress', { stage: 'session', session_id: session.id })
  let current = await request('GET', `/api/v1/studio/sessions/${session.id}/video-project`)
  if (!current.asset_id) {
    const source = await request('GET', '/api/v1/studio/sessions/fa73025d-eaec-4a14-a307-06d46a329d3e/video-project')
    current = await request('PUT', `/api/v1/studio/sessions/${session.id}/video-project`, { request_id: crypto.randomUUID(), expected_version: 0, project: { ...source.project, name: '工作台宽度验收' } })
  }
  const previewMedia = current.project.shots[1].media
  await request('POST', `/api/v1/studio/sessions/${session.id}/assets/references`, { asset_id: previewMedia.assetId, asset_version_id: previewMedia.versionId, request_id: `native-workspace-media:${session.id}:${previewMedia.versionId}` })
  await emit('studio:layout-progress', { stage: 'project' })
  history.pushState({}, '', `/studio/sessions/${session.id}?panel=video`); dispatchEvent(new PopStateEvent('popstate'))
  await wait(() => document.querySelectorAll('[data-track="video"]').length === 5 && document.querySelector('.studio-chat-root'), '真实视频编辑器没有打开')
  assert(Math.abs(chatWidth() - 380) < 1, `Chat 默认宽度应为380px，当前${chatWidth()}px`)
  measurements.push({ stage: 'default', chat: chatWidth() })
  await emit('studio:layout-progress', { stage: 'default', chat: chatWidth() })
  const paneRect = document.querySelector('#studio-chat-pane').getBoundingClientRect()
  const headerButtons = [...document.querySelectorAll('#studio-chat-pane > div > header button')].filter(element => element.getBoundingClientRect().width > 0)
  assert(headerButtons.length > 0, 'Chat头部按钮没有显示')
  assert(headerButtons.every(element => element.getBoundingClientRect().right <= paneRect.right + 1), 'Chat头部按钮溢出')
  const checkComposer = () => {
    const root = document.querySelector('.studio-chat-root'), composer = root.querySelector('[data-slot="studio-composer"]'), form = composer.querySelector('form')
    const bounds = form.getBoundingClientRect()
    const buttons = [...form.querySelectorAll('button')].filter(element => element.getBoundingClientRect().width > 0)
    assert(buttons.length >= 6 && buttons.every(element => { const rect = element.getBoundingClientRect(); return rect.left >= bounds.left - 1 && rect.right <= bounds.right + 1 }), '输入区按钮超出边界')
    assert(root.firstElementChild.getBoundingClientRect().bottom <= composer.getBoundingClientRect().top + 1, '输入区覆盖了消息区域')
    const model = form.querySelector('[aria-label^="选择模型："]').getBoundingClientRect(), send = aria('发送消息').getBoundingClientRect()
    assert(Math.abs(model.y + model.height / 2 - send.y - send.height / 2) < 3, '模型选择与发送按钮的位置异常')
  }
  checkComposer()
  await emit('studio:layout-progress', { stage: 'composer-layout' })
  const composer = aria('输入消息')
  composer.focus(); document.execCommand('insertText', false, '保留这条尚未发送的输入')
  const chatNode = document.querySelector('.studio-chat-root')
  const handle = aria('调整对话与工作台宽度')
  assert(handle?.getAttribute('role') === 'separator', '宽度分隔线缺失')
  handle.focus(); handle.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }))
  await delay(200)
  assert(Math.abs(chatWidth() - 380) < 1, 'Chat宽度小于380px')
  handle.focus(); handle.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }))
  await wait(() => chatWidth() > 400, '键盘没有调整宽度')
  measurements.push({ stage: 'keyboard', chat: chatWidth() })
  for (let index = 0; index < 10 && document.querySelector('#studio-workbench-pane').getBoundingClientRect().width > 401; index++) {
    handle.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true })); await delay(100)
  }
  const minimum = document.querySelector('#studio-workbench-pane').getBoundingClientRect()
  assert(Math.abs(minimum.width - 400) < 1, '右侧工作台最小宽度异常')
  const closeRect = aria('收起右侧面板').getBoundingClientRect()
  assert([...document.querySelectorAll('#studio-workbench-pane [role="tab"]')].every(element => { const rect = element.getBoundingClientRect(); return rect.left >= minimum.left && rect.right <= closeRect.left }), '右侧最小宽度下标签被关闭按钮覆盖')
  measurements.push({ stage: 'minimum', workbench: minimum.width })
  handle.dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))
  await wait(() => Math.abs(chatWidth() - 380) < 1, '双击分隔线没有恢复默认宽度')
  handle.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }))
  await wait(() => chatWidth() > 400, '手动调整宽度没有生效')
  const preferred = chatWidth()
  const editing = aria('视频编辑器')
  await wait(() => editing.querySelector('.sve-preview video')?.readyState >= 2, '已有视频没有加载')
  aria('播放视频').click()
  await wait(() => aria('暂停视频'), '已有视频没有播放')
  choose('项目资产')
  await wait(() => tab('项目资产').getAttribute('aria-selected') === 'true', '项目资产没有打开')
  await wait(() => editing.querySelector('[aria-label="播放视频"]'), '离开编辑器没有暂停预览')
  assert(Math.abs(chatWidth() - preferred) < 1, '切换项目资产改变了宽度')
  choose('会话任务')
  await wait(() => tab('会话任务').getAttribute('aria-selected') === 'true', '会话任务没有打开')
  assert(Math.abs(chatWidth() - preferred) < 1, '切换会话任务改变了宽度')
  choose('视频编辑器')
  await wait(() => tab('视频编辑器').getAttribute('aria-selected') === 'true', '视频编辑器没有打开')
  assert(Math.abs(chatWidth() - preferred) < 1, '切换视频编辑器改变了宽度')
  assert(aria('视频编辑器') === editing, '切换标签重建了编辑器')
  await emit('studio:layout-progress', { stage: 'stable-tabs', chat: chatWidth() })
  const mediaAsset = await request('GET', `/api/v1/studio/assets/${current.project.shots[1].media.assetId}`)
  if (editing.querySelector('.sve-assets-pane').dataset.collapsed === 'true') editing.querySelector('[aria-label="展开项目资产"]').click()
  await wait(() => [...editing.querySelectorAll('[aria-label^="预览资产："]')].some(element => element.getAttribute('aria-label') === `预览资产：${mediaAsset.name}`), '项目视频资产没有显示')
  const previewButton = [...editing.querySelectorAll('[aria-label^="预览资产："]')].find(element => element.getAttribute('aria-label') === `预览资产：${mediaAsset.name}`)
  previewButton.click()
  await wait(() => editing.querySelector('.sve-preview video[controls]')?.readyState >= 2, '项目视频资产没有加载')
  const assetMedia = editing.querySelector('.sve-preview video[controls]')
  await assetMedia.play()
  assert(!assetMedia.paused, '项目视频资产没有播放')
  choose('项目资产')
  await wait(() => assetMedia.paused, '隐藏编辑器没有暂停项目资产预览')
  choose('视频编辑器')
  await wait(() => tab('视频编辑器').getAttribute('aria-selected') === 'true', '项目资产预览后不能返回编辑器')
  await emit('studio:layout-progress', { stage: 'media-paused' })
  const editor = aria('视频编辑器')
  aria('收起右侧面板').click()
  await wait(() => aria('展开右侧面板') && chatWidth() > 800, '收起右侧面板没有扩展Chat')
  assert(editor.isConnected, '收起面板卸载了视频编辑器')
  aria('展开右侧面板').click()
  await wait(() => Math.abs(chatWidth() - preferred) < 1, '重新展开没有保留手动调整的宽度')
  await emit('studio:layout-progress', { stage: 'expanded', chat: chatWidth() })
  assert(aria('视频编辑器') === editor && document.querySelector('.studio-chat-root') === chatNode, '宽度切换重建了编辑器或Chat')
  assert(aria('输入消息').textContent.includes('保留这条尚未发送的输入'), '宽度切换丢失Chat输入')
  const chatRect = chatNode.getBoundingClientRect(), sendRect = aria('发送消息').getBoundingClientRect()
  assert(sendRect.right <= chatRect.right + 1 && sendRect.left >= chatRect.left - 1, 'Chat中的发送按钮溢出')
  assert(chatNode.scrollWidth <= chatNode.clientWidth + 1, 'Chat存在横向溢出')
  checkComposer()
  await emit('studio:layout-size', [1000, 800])
  await wait(() => window.innerWidth === 1000 && chatWidth() > 900, '窄窗口Chat没有展开')
  measurements.push({ stage: 'narrow', chat: chatWidth() })
  aria('打开创作工作台').click()
  await wait(() => document.querySelector('[role="dialog"] [aria-label="视频编辑器"]'), '窄窗口不能打开视频编辑器')
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  await wait(() => !document.querySelector('[role="dialog"]'), '窄窗口工作台没有关闭')
  await emit('studio:layout-size', [1440, 940])
  await delay(1000)
  await emit('studio:layout-progress', { stage: 'desktop-restored', window_width: window.innerWidth, chat: chatWidth(), preferred })
  await wait(() => window.innerWidth === 1440 && Math.abs(chatWidth() - preferred) < 1, '恢复桌面窗口后没有保留宽度')
  checkComposer()
  await emit('studio:layout-result', { success: true, session_id: session.id, default_chat_width: 380, preferred_chat_width: preferred, stable_tabs: true, keyboard_resize: true, minimum_workbench_width: 400, double_click_reset: true, editor_preserved: true, composer_preserved: true, composer_layout: true, responsive: true, measurements })
})().catch(error => window.__TAURI_INTERNALS__.invoke('plugin:event|emit', { event: 'studio:layout-result', payload: { success: false, error: String(error), chat_width: document.querySelector('.studio-chat-root')?.getBoundingClientRect().width, page_text: document.body.innerText.slice(-1600) } }))
