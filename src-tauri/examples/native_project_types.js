void (async () => {
  if (window.__PIXOMA_PROJECT_TYPES_RUNNING__) return
  window.__PIXOMA_PROJECT_TYPES_RUNNING__ = true
  const invoke = window.__TAURI_INTERNALS__.invoke
  const emit = (event, payload) => invoke('plugin:event|emit', { event, payload })
  const request = (method, path, body = null) => invoke('studio_request', { request: { method, path, body } })
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
  const wait = async (condition, message) => {
    const end = Date.now() + 20000
    while (!await condition()) {
      if (Date.now() > end) throw new Error(message)
      await delay(100)
    }
    await delay(100)
  }
  const visible = element => element.getClientRects().length > 0 && !element.closest('[inert], [aria-hidden="true"]')
  const aria = label => [...document.querySelectorAll('[aria-label]')].find(element => element.getAttribute('aria-label') === label && visible(element))
  const button = (label, scope = document) => [...scope.querySelectorAll('button')].find(element => element.textContent.trim() === label && visible(element))
  const tab = label => [...document.querySelectorAll('[role="tab"]')].find(element => element.textContent.trim() === label && visible(element))
  const choose = label => tab(label).dispatchEvent(new MouseEvent('mousedown', { bubbles: true, button: 0, ctrlKey: false }))
  const navigate = async session => {
    history.pushState({}, '', `/studio/sessions/${session.id}`)
    dispatchEvent(new PopStateEvent('popstate'))
    await wait(() => document.querySelector('.studio-chat-root'), '会话没有打开')
  }
  const fill = value => {
    const input = document.querySelector('#studio-project-name')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value)
    input.dispatchEvent(new Event('input', { bubbles: true }))
  }
  const save = async () => {
    const form = document.querySelector('#studio-project-name').closest('form')
    await wait(() => !form.querySelector('[type="submit"]').disabled, '项目不能保存')
    form.requestSubmit()
    await wait(() => !document.querySelector('#studio-project-name'), '项目表单没有关闭')
  }
  const create = async (name, type) => {
    aria('新建项目').click()
    await wait(() => document.querySelector('#studio-project-name'), '项目表单没有打开')
    const dialog = document.querySelector('[role="dialog"]')
    assert(button('通用', dialog).dataset.state === 'on', '项目默认类型不是通用')
    fill(name)
    if (type === 'video') button('视频', dialog).click()
    await wait(() => button(type === 'video' ? '视频' : '通用', dialog).dataset.state === 'on', '类型没有选中')
    button(type === 'video' ? '视频' : '通用', dialog).click()
    await delay(100)
    assert(button(type === 'video' ? '视频' : '通用', dialog).dataset.state === 'on', '重复点击改变了项目类型')
    await save()
    const projects = await request('GET', '/api/v1/studio/projects')
    const project = projects.find(item => item.name === name)
    assert(project?.project_type === type, '项目类型没有保存')
    return project
  }
  await wait(() => aria('新建项目'), 'Studio没有启动')
  const suffix = Date.now()
  const general = await create(`通用类型验收${suffix}`, 'general')
  const video = await create(`视频类型验收${suffix}`, 'video')
  const generalSession = await request('POST', '/api/v1/studio/sessions', { request_id: `general:${general.id}` })
  const videoSession = await request('POST', '/api/v1/studio/sessions', { request_id: `video:${video.id}` })
  await request('PATCH', `/api/v1/studio/sessions/${generalSession.id}/project`, { project_id: general.id })
  await request('PATCH', `/api/v1/studio/sessions/${videoSession.id}/project`, { project_id: video.id })
  const documentAsset = await request('POST', '/api/v1/studio/assets/text', { session_id: generalSession.id, name: '通用项目资料.md', content: '# 茶品牌创作资料\n\n包含文案、图片、音频与视频。', request_id: `document:${general.id}` })
  const source = await request('GET', '/api/v1/studio/sessions/fa73025d-eaec-4a14-a307-06d46a329d3e/video-project')
  const savedVideo = await request('PUT', `/api/v1/studio/sessions/${videoSession.id}/video-project`, { request_id: `project:${video.id}`, expected_version: 0, project: { ...source.project, name: '项目类型验收视频' } })
  await navigate(generalSession)
  await wait(() => tab('项目资产')?.getAttribute('aria-selected') === 'true' && document.querySelector('[data-slot="studio-workbench-panel"]')?.textContent.includes('通用项目资料.md'), '通用项目默认工作区没有展示资料')
  await navigate(videoSession)
  await wait(() => tab('视频编辑器')?.getAttribute('aria-selected') === 'true' && document.querySelectorAll('[data-track="video"]').length === 5, '视频项目没有默认打开五个分镜')
  const editor = document.querySelector('[aria-label="视频编辑器"]')
  await emit('studio:layout-progress', { stage: 'project-defaults', general: general.id, video: video.id })
  aria(`${video.name}的更多操作`).dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, button: 0, pointerType: 'mouse', ctrlKey: false }))
  await wait(() => [...document.querySelectorAll('[role="menuitem"]')].some(element => element.textContent.trim() === '编辑项目'), '项目菜单没有打开')
  const edit = [...document.querySelectorAll('[role="menuitem"]')].find(element => element.textContent.trim() === '编辑项目')
  edit.click()
  await wait(() => document.querySelector('#studio-project-name'), '项目编辑没有打开')
  const dialog = document.querySelector('[role="dialog"]')
  assert(button('视频', dialog).dataset.state === 'on', '编辑项目没有恢复保存的类型')
  fill(`混合类型验收${suffix}`)
  button('通用', dialog).click()
  await save()
  await wait(() => tab('项目资产')?.getAttribute('aria-selected') === 'true', '项目改为通用后没有更新默认工作区')
  const updated = (await request('GET', '/api/v1/studio/projects')).find(item => item.id === video.id)
  assert(updated.project_type === 'general' && updated.name === `混合类型验收${suffix}`, '项目修改没有保存')
  const after = await request('GET', `/api/v1/studio/sessions/${videoSession.id}/video-project`)
  assert(JSON.stringify(after) === JSON.stringify(savedVideo), '修改项目类型改变了已有视频工程')
  assert(editor.isConnected, '修改项目类型卸载了视频编辑器')
  choose('视频编辑器')
  await wait(() => tab('视频编辑器').getAttribute('aria-selected') === 'true', '通用项目不能手动打开视频编辑器')
  assert(document.querySelector('[aria-label="视频编辑器"]') === editor, '手动切换重建了编辑器')
  await navigate(generalSession)
  await wait(() => tab('项目资产')?.getAttribute('aria-selected') === 'true', '通用会话没有恢复默认资产面板')
  await emit('studio:layout-size', [1000, 800])
  await wait(() => innerWidth === 1000, '窗口没有缩小')
  aria('打开创作工作台').click()
  await wait(() => document.querySelector('[role="dialog"] [role="tab"]'), '移动工作台没有打开')
  await wait(() => document.querySelector('[role="dialog"] [role="tab"][aria-selected="true"]')?.textContent === '项目资产', '移动默认面板与桌面不同')
  choose('视频编辑器')
  await wait(() => location.search.includes('panel=video'), '移动标签没有更新会话面板')
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  await wait(() => !document.querySelector('[role="dialog"]'), '移动工作台没有关闭')
  await emit('studio:layout-size', [1440, 940])
  await wait(() => innerWidth === 1440 && tab('视频编辑器')?.getAttribute('aria-selected') === 'true', '桌面没有保留移动端选择的面板')
  assert(Math.abs(document.querySelector('.studio-chat-root').getBoundingClientRect().width - 380) < 1, 'Chat最小默认宽度异常')
  const assets = await request('GET', `/api/v1/studio/sessions/${generalSession.id}`)
  assert(assets.assets.some(item => item.id === documentAsset.id), '通用项目资料没有保留')
  await emit('studio:layout-result', { success: true, project_types: ['general', 'video'], default_type: 'general', shared_assets: true, existing_video_preserved: true, manual_editor_access: true, responsive_panel_sync: true })
})().catch(error => window.__TAURI_INTERNALS__.invoke('plugin:event|emit', { event: 'studio:layout-result', payload: { success: false, error: String(error), location: location.href, page_text: document.body.innerText.slice(-1800) } }))
