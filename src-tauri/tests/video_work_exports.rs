use pixoma_studio::Store;
use serde_json::json;

#[tokio::test]
async fn work_exports_keep_snapshots_and_results_after_main_chat_removal() -> Result<(),Box<dyn std::error::Error>> {
    let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../.local-cache");
    std::fs::create_dir_all(&root)?;
    let directory = tempfile::Builder::new().prefix("work-export-").tempdir_in(root)?;
    let path = directory.path().join("studio.sqlite");
    let store = Store::open(&path).await?;
    let session = store.create_session("export-owner").await?;
    let video = store.create_asset_bytes(Some(&session.id),"茶园.mp4",include_bytes!("fixtures/red.mp4"),"user","export-source").await?;
    let version = &video.versions[0];
    let project = json!({"version":2,"name":"导出恢复","width":128,"height":128,"fps":30,"audio":[],"shots":[{"id":"opening","name":"开场","script":"","storyboard":"茶园晨光","references":[],"subtitle":"清晨","duration":1,"sourceIn":0,"inputs":{},"media":{"assetId":video.id,"versionId":version.id,"url":version.content_url,"duration":1}}]});
    let work = store.write_video_project(&session.id,"save-project",json!({"expected_version":0,"project":project})).await?;
    let video_id = work["asset_id"].as_str().ok_or("作品标识缺失")?;
    let export_request = json!({"request_id":"work-export","session_id":session.id,"name":"导出恢复.mp4","width":128,"height":128,"fps":30,"shots":[{"asset_id":video.id,"asset_version_id":version.id,"source_in":0,"duration":1,"subtitle":"清晨","volume":1}],"audio":[]});
    let submission = json!({"session_id":session.id,"request":export_request,"project":project,"source_version":1});
    let exported = store.export_video_work(video_id,submission.clone()).await?;
    assert_eq!(exported["status"],"completed");
    assert_eq!(exported["project"],project);
    let result = exported["result"].clone();
    assert_eq!(store.export_video_work(video_id,submission).await?["result"],result);
    let mut legacy_request = export_request.clone();
    legacy_request["request_id"] = json!("legacy-export");
    let legacy = store.export_video_project(legacy_request.clone()).await?;
    let registered = store.export_video_work(video_id,json!({"session_id":session.id,"request":legacy_request,"project":project,"source_version":1,"register_only":true})).await?;
    assert_eq!(registered["result"]["assetId"],legacy["id"]);
    let mut missing_request = export_request.clone(); missing_request["request_id"] = json!("missing-legacy");
    assert!(store.export_video_work(video_id,json!({"session_id":session.id,"request":missing_request,"project":project,"source_version":1,"register_only":true})).await.is_err());
    let mut changed = project.clone(); changed["shots"][0]["storyboard"] = json!("新的描述");
    store.write_video_work(video_id,&session.id,"edit-after-export",json!({"expected_version":1,"project":changed})).await?;
    let mut invalid = json!({"session_id":session.id,"request":export_request,"project":project,"source_version":1});
    invalid["request"]["shots"][0]["duration"] = json!(0.5);
    assert!(store.export_video_work(video_id,invalid).await.is_err());
    let mut failure_project = project.clone();
    failure_project["shots"][0]["sourceIn"] = json!(2);
    let mut failure_request = export_request.clone();
    failure_request["request_id"] = json!("failed-export");
    failure_request["shots"][0]["source_in"] = json!(2);
    assert!(store.export_video_work(video_id,json!({"session_id":session.id,"request":failure_request,"project":failure_project,"source_version":1})).await.is_err());
    let failed = store.get_video_work_export(video_id,"failed-export").await?;
    assert_eq!(failed["status"],"failed");
    assert!(failed["error"].as_str().is_some_and(|error|error.contains("剪辑范围超出源视频")));
    let other = store.create_session("unrelated-export").await?;
    assert!(store.export_video_work(video_id,json!({"session_id":other.id,"request":export_request,"project":project,"source_version":1})).await.is_err());
    let video_id = video_id.to_owned();
    store.clear_sessions().await?;
    store.close().await;
    let store = Store::open(&path).await?;
    let history = store.list_video_work_exports(&video_id).await?;
    assert_eq!(history.as_array().ok_or("导出历史缺失")?.len(),3);
    let completed = store.get_video_work_export(&video_id,"work-export").await?;
    assert_eq!(completed["project"],project);
    assert_eq!(completed["result"],result);
    assert_eq!(completed["status"],"completed");
    assert_eq!(store.get_video_work_export(&video_id,"failed-export").await?["status"],"failed");
    let api = pixoma_studio::LocalApi::new(store.clone());
    let listed = api.request(pixoma_studio::LocalRequest {method:"GET".into(),path:format!("/api/v1/studio/video-projects/{video_id}/exports"),body:None}).await?;
    assert_eq!(listed,history);
    let reopened = store.open_video_work(&video_id).await?;
    let new_session = reopened["main_session_id"].as_str().ok_or("恢复的主对话缺失")?;
    let resumed = store.export_video_work(&video_id,json!({"session_id":new_session,"request":export_request,"project":project,"source_version":1})).await?;
    assert_eq!(resumed["result"],result);
    assert_eq!(store.read_video_work(&video_id).await?["project"],changed);
    assert!(!store.read_asset(result["assetId"].as_str().ok_or("导出资产缺失")?,result["versionId"].as_str().ok_or("导出版本缺失")?).await?.is_empty());
    store.close().await;
    Ok(())
}
