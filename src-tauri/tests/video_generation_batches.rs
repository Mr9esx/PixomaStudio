use pixoma_studio::Store;
use serde_json::{Value,json};

#[tokio::test]
async fn batches_freeze_all_inputs_atomically_and_survive_reopening() -> Result<(),Box<dyn std::error::Error>> {
    let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../.local-cache");
    std::fs::create_dir_all(&root)?;
    let directory = tempfile::Builder::new().prefix("video-batch-").tempdir_in(root)?;
    let path = directory.path().join("studio.sqlite");
    let store = Store::open(&path).await?;
    let definition: Value = serde_json::from_str(include_str!("../../docs/video-generation/h3/tea-h3-workflow.json"))?;
    let workflow = store.create_workflow(json!({"name":"批量视频工作流","category":"video","enabled":false,"draft":definition})).await?;
    let workflow_id = workflow["id"].as_str().ok_or("工作流缺失")?;
    let version = store.create_workflow_version(workflow_id,json!({"expected_revision":1,"version":"1.0.0"})).await?;
    let session = store.create_session("batch-owner").await?;
    let mut shots: Vec<Value> = ["晨光","采茶","茶馆","待填写"].iter().enumerate().map(|(index,name)|json!({"id":format!("shot-{index}"),"name":name,"script":"","storyboard":name,"subtitle":"","references":[],"duration":0,"sourceIn":0,"inputs":{"prompt":name},"workflowId":workflow_id,"versionId":version["id"]})).collect();
    shots[3]["inputs"] = json!({});
    let project = json!({"version":2,"name":"批量生成","width":1280,"height":720,"fps":30,"shots":shots,"audio":[]});
    let work = store.write_video_project(&session.id,"initial",json!({"expected_version":0,"project":project})).await?;
    let id = work["asset_id"].as_str().ok_or("作品缺失")?;
    let request = json!({"request_id":"batch","session_id":session.id,"expected_version":1,"shot_ids":["shot-1","shot-0"]});
    let other = store.create_session("unrelated-batch").await?;
    let mut invalid = request.clone(); invalid["session_id"] = json!(other.id);
    assert!(store.prepare_video_generation_batch(id,invalid).await.is_err());
    for ids in [json!([]),json!(["shot-0","shot-0"]),json!(["shot-0","missing"]),json!(["shot-0","shot-3"])] {
        let mut invalid = request.clone(); invalid["shot_ids"] = ids;
        assert!(store.prepare_video_generation_batch(id,invalid).await.is_err());
        assert_eq!(store.list_video_generations(id).await?,json!([]));
    }
    let (left,right) = tokio::join!(store.prepare_video_generation_batch(id,request.clone()),store.prepare_video_generation_batch(id,request.clone()));
    let batch = left?;
    assert_eq!(batch,right?);
    assert_eq!(batch["generations"][0]["shot_id"],"shot-0");
    assert_eq!(batch["generations"][1]["shot_id"],"shot-1");
    assert_eq!(batch["generations"][0]["snapshot"]["inputs"]["prompt"],"晨光");
    let mut overlapping = request.clone(); overlapping["request_id"] = json!("overlapping"); overlapping["shot_ids"] = json!(["shot-2","shot-0"]);
    assert!(store.prepare_video_generation_batch(id,overlapping).await.is_err());
    assert_eq!(store.list_video_generations(id).await?.as_array().ok_or("记录缺失")?.len(),2);
    let mut different = request.clone(); different["shot_ids"] = json!(["shot-2"]);
    assert!(store.prepare_video_generation_batch(id,different).await.is_err());
    let mut changed = project.clone(); changed["shots"][0]["inputs"]["prompt"] = json!("手工更新");
    store.write_video_work(id,&session.id,"changed",json!({"expected_version":1,"project":changed})).await?;
    assert_eq!(store.prepare_video_generation_batch(id,request).await?,batch);
    let api = pixoma_studio::LocalApi::new(store.clone());
    let listed = api.request(pixoma_studio::LocalRequest {method:"GET".into(),path:format!("/api/v1/studio/video-projects/{id}/generation-batches"),body:None}).await?;
    assert_eq!(listed,json!([batch]));
    let id = id.to_owned();
    store.close().await;
    let store = Store::open(&path).await?;
    store.resume_video_generations().await?;
    let restored = store.get_video_generation_batch(&id,"batch").await?;
    assert!(restored["generations"].as_array().ok_or("批量记录缺失")?.iter().all(|generation|generation["status"] == "submission_failed" && generation["submission_error"].as_str().is_some_and(|error|error.contains("停用"))));
    assert_eq!(restored["generations"][0]["snapshot"],batch["generations"][0]["snapshot"]);
    assert_eq!(store.read_video_work(&id).await?["project"]["shots"][0]["inputs"]["prompt"],"手工更新");
    let api = pixoma_studio::LocalApi::new(store.clone());
    let templates = api.request(pixoma_studio::LocalRequest {method:"GET".into(),path:"/api/v1/studio/generation-templates".into(),body:None}).await?;
    let template = templates.as_array().ok_or("模板列表缺失")?.iter().find(|template|template["definition"]["execution"]["capability"]=="first_frame").ok_or("首帧视频模板缺失")?;
    let child_workflow = store.create_workflow(json!({"name":"下游首帧工作流","category":"video","enabled":false,"draft":template["definition"]})).await?;
    let child_version = store.create_workflow_version(child_workflow["id"].as_str().ok_or("下游工作流缺失")?,json!({"expected_revision":1,"version":"1.0.0"})).await?;
    let mut dependent_project = store.read_video_work(&id).await?["project"].clone();
    dependent_project["shots"][1]["workflowId"] = child_workflow["id"].clone();
    dependent_project["shots"][1]["versionId"] = child_version["id"].clone();
    dependent_project["shots"][2]["workflowId"] = child_workflow["id"].clone();
    dependent_project["shots"][2]["versionId"] = child_version["id"].clone();
    store.write_video_work(&id,&session.id,"dependency-settings",json!({"expected_version":2,"project":dependent_project})).await?;
    let binding = json!({"shot_id":"shot-1","source_shot_id":"shot-0","input_key":"first_frame","position":"last","fps":30});
    let waiting = store.prepare_video_generation_batch(&id,json!({"request_id":"dependent","session_id":session.id,"expected_version":3,"shot_ids":["shot-0","shot-1"],"dependencies":[binding]})).await?;
    assert_eq!(waiting["generations"][1]["status"],"waiting_dependencies");
    assert!(waiting["generations"][1]["execution_id"].is_null());
    let child = waiting["generations"][1]["id"].as_str().ok_or("下游记录缺失")?;
    assert_eq!(store.submit_video_generation(&id,child).await?["status"],"waiting_dependencies");
    assert!(store.retry_video_generation(&id,child,json!({"request_id":"invalid-retry","session_id":session.id})).await.is_err());
    store.resume_video_generations().await?;
    store.resume_video_generations().await?;
    let blocked = store.get_video_generation(&id,child).await?;
    assert_eq!(blocked["status"],"blocked_dependencies");
    assert!(blocked["dependency_error"].as_str().is_some_and(|error|error.contains("上游分镜")));
    assert!(blocked["execution_id"].is_null());
    let cancelled_batch = store.prepare_video_generation_batch(&id,json!({"request_id":"cancel-dependent","session_id":session.id,"expected_version":3,"shot_ids":["shot-0","shot-1","shot-2"],"dependencies":[binding,{"shot_id":"shot-2","source_shot_id":"shot-1","input_key":"first_frame","position":"first","fps":30}]})).await?;
    let cancelled_child = cancelled_batch["generations"][1]["id"].as_str().ok_or("下游记录缺失")?;
    let cancelled = store.cancel_video_dependency_wait(&id,cancelled_child,json!({"session_id":session.id})).await?;
    assert_eq!(cancelled["status"],"cancelled");
    assert!(cancelled["execution_id"].is_null());
    store.resume_video_generations().await?;
    let downstream = store.get_video_generation(&id,cancelled_batch["generations"][2]["id"].as_str().ok_or("后续任务缺失")?).await?;
    assert_eq!(downstream["status"],"blocked_dependencies");
    assert!(downstream["execution_id"].is_null());
    assert!(downstream["dependency_error"].as_str().is_some_and(|error|error.contains("已取消")));
    store.clear_sessions().await?;
    assert_eq!(store.list_video_generation_batches(&id).await?.as_array().ok_or("批次缺失")?.len(),3);
    assert_eq!(store.get_video_generation(&id,child).await?["status"],"blocked_dependencies");
    store.close().await;
    Ok(())
}
